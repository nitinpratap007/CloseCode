export function detectLanguage(filePath: string): string {
  const ext = filePath.split(".").pop()?.toLowerCase() ?? "";
  const map: Record<string, string> = {
    js: "javascript",
    mjs: "javascript",
    cjs: "javascript",
    jsx: "javascript",
    ts: "typescript",
    tsx: "typescript",
    json: "json",
    html: "html",
    htm: "html",
    css: "css",
    scss: "scss",
    less: "less",
    md: "markdown",
    py: "python",
    rb: "ruby",
    go: "go",
    rs: "rust",
    java: "java",
    c: "c",
    h: "c",
    cpp: "cpp",
    hpp: "cpp",
    cs: "csharp",
    php: "php",
    sh: "shell",
    bat: "bat",
    ps1: "powershell",
    yml: "yaml",
    yaml: "yaml",
    xml: "xml",
    sql: "sql",
    vue: "html",
    svg: "xml",
    toml: "ini",
    ini: "ini",
    env: "shell",
    dockerfile: "dockerfile",
    gitignore: "plaintext",
  };
  return map[ext] ?? "plaintext";
}